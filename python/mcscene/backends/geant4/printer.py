"""Печать C++ проекта Geant4 из готового плана (пункт 1.5 плана).

Неизменный каркас (CMakeLists, стенд, заголовки) — шаблоны в templates/ с
подстановками вида @{name}. Тела, материалы, мир и пробные точки печатаются
из Python: так их проще держать читаемыми.

Правила печати:
  - числа: целое -> 25, иначе кратчайшая точная запись, -0.0 -> 0 (cppfmt.num);
  - единицы всегда явные: *mm;
  - тела в порядке плана (родитель раньше ребёнка);
  - над каждым телом комментарий: id, имя из FreeCAD, материал, размеры;
  - никаких дат и абсолютных путей: две генерации одной сцены совпадают байт в байт.
"""
from __future__ import annotations

import json
from dataclasses import asdict
from pathlib import Path
from string import Template

from ...diagnostics import Diagnostic
from ...passes.naming import WORLD
from ...passes.rotations import IDENTITY
from . import cppfmt as f
from .plan import BodyPlan, G4Plan

TEMPLATES = Path(__file__).resolve().parent / "templates"

GENERATED = "generated/GeneratedDetectorConstruction.cc"
GENERATED_HH = "generated/GeneratedDetectorConstruction.hh"
EXPECTED_HH = "generated/ExpectedChecks.hh"
HARNESS = "harness/check_geometry.cc"
CMAKE = "CMakeLists.txt"
REPORT = "report.json"
USER_HH = "user/DetectorConstruction.hh"
APP_MAIN = "app/main.cc"
VIS_MAC = "app/vis.mac"
BATCH_MAC = "app/batch.mac"

# Цвета тел по материалам (r, g, b): различимые и стабильные от запуска к запуску.
PALETTE = [(0.12, 0.47, 0.71), (1.0, 0.5, 0.05), (0.17, 0.63, 0.17), (0.84, 0.15, 0.16),
           (0.58, 0.4, 0.74), (0.55, 0.34, 0.29), (0.89, 0.47, 0.76), (0.5, 0.5, 0.5),
           (0.74, 0.74, 0.13), (0.09, 0.75, 0.81)]
PARENT_OPACITY = 0.3     # тела, внутри которых есть другие тела, — полупрозрачные


class _T(Template):
    delimiter = "@"


def _template(name: str, **subs: str) -> str:
    text = (TEMPLATES / name).read_text(encoding="utf-8")
    return _T(text).substitute(**subs)


def header(plan: G4Plan, comment: str = "//") -> str:
    text = (
        "%s GENERATED by mcscene %s — DO NOT EDIT (перезаписывается при mcscene generate --force)\n"
        "%s источник: %s, формат %s, sha256 %s"
        % (comment, plan.generator_version, comment, plan.input_name, plan.format_version,
           plan.input_sha256))
    if plan.unsafe:
        text += ("\n%s ВНИМАНИЕ: --unsafe-skip-checks — геометрические ошибки контракта пропущены,"
                 " только для отладки" % comment)
    return text


def render(plan: G4Plan, diagnostics: list[Diagnostic]) -> dict[str, str]:
    """Все файлы проекта, кроме user/ и копии g4scene: путь -> текст."""
    return {
        CMAKE: _template("CMakeLists.txt.in", header=header(plan, "#"), scene_name=plan.scene_name),
        GENERATED_HH: _template("GeneratedDetectorConstruction.hh.in", header=header(plan),
                                body_decls="\n".join("  void %s();" % b.func for b in plan.bodies)),
        GENERATED: render_construction(plan),
        EXPECTED_HH: render_expected(plan),
        HARNESS: _template("check_geometry.cc.in", header=header(plan)),
        APP_MAIN: _template("app_main.cc.in", header=header(plan)),
        VIS_MAC: render_vis_mac(plan),
        BATCH_MAC: _template("batch.mac.in", header=header(plan, "#")),
        REPORT: render_report(plan, diagnostics),
    }


def render_user_header() -> str:
    return _template("DetectorConstruction.hh.in")


# --- GeneratedDetectorConstruction.cc -------------------------------------------------
def render_construction(plan: G4Plan) -> str:
    out = [header(plan), "",
           '#include "GeneratedDetectorConstruction.hh"', "",
           '#include "G4Box.hh"',
           '#include "G4LogicalVolume.hh"',
           '#include "G4PVPlacement.hh"',
           '#include "G4SystemOfUnits.hh"',
           '#include "G4ThreeVector.hh"', "",
           '#include "g4scene/Materials.hh"',
           '#include "g4scene/Transform.hh"', ""]

    out += ["G4VPhysicalVolume* GeneratedDetectorConstruction::Construct() {",
            "  BuildMaterials();",
            "  %-40s// хук для user/" % "ConfigureMaterials();",
            "  G4VPhysicalVolume* world = BuildWorld();"]
    out += ["  %s();" % b.func for b in plan.bodies]
    out += ["  %-40s// хук для user/" % ("PostConstruct(LV(%s));" % f.cpp_str(WORLD)),
            "  return world;", "}", ""]

    out += ["void GeneratedDetectorConstruction::BuildMaterials() {"]
    width = max(len("fReg.AddMaterial(%s, %s);" % (f.cpp_str(m.id), m.cpp)) for m in plan.materials)
    for m in plan.materials:
        stmt = "fReg.AddMaterial(%s, %s);" % (f.cpp_str(m.id), m.cpp)
        out.append(("  %-*s  // %s" % (width, stmt, m.comment)).rstrip())
    out += ["}", ""]

    w = plan.world
    lo, hi = w.extent
    out += ["G4VPhysicalVolume* GeneratedDetectorConstruction::BuildWorld() {",
            "  // мир: тела занимают [%s]..[%s] мм, запас %s %%" % (
                ", ".join(f.num(x) for x in lo), ", ".join(f.num(x) for x in hi),
                f.num(w.margin_percent)),
            "  auto* solid = new G4Box(%s, %s);" % (
                f.cpp_str(WORLD), ", ".join(f.mm(x) for x in w.half_size)),
            "  auto* lv = new G4LogicalVolume(solid, Mat(%s), %s);" % (
                f.cpp_str(w.material), f.cpp_str(WORLD)),
            "  fReg.AddVolume(%s, lv);" % f.cpp_str(WORLD),
            "  return new G4PVPlacement(nullptr, G4ThreeVector(), lv, %s, nullptr, false, 0);"
            % f.cpp_str(WORLD),
            "}"]

    for b in plan.bodies:
        out += [""] + render_body(b)
    return "\n".join(out) + "\n"


def render_body(b: BodyPlan) -> list[str]:
    name = f.cpp_str(b.volume)
    lines = ["// %s" % f.comment(b.title),
             "void GeneratedDetectorConstruction::%s() {" % b.func,
             "  // %s" % b.solid.comment,
             "  auto* solid = %s;" % b.solid.cpp,
             "  auto* lv = new G4LogicalVolume(solid, Mat(%s), %s);" % (f.cpp_str(b.material_id), name),
             "  fReg.AddVolume(%s, lv);" % name]
    if b.matrix == IDENTITY:
        rotation = "scene::kIdentity"
    else:
        lines.append("  // поворот «тело -> родитель», %s" % b.rotation_note)
        lines += _matrix_literal("  const scene::Mat3 rotation", b.matrix)
        rotation = "rotation"
    lines += ["  // центр тела в системе родителя «%s»" % b.mother,
              "  scene::Place(lv, LV(%s), %s," % (f.cpp_str(b.mother), name),
              "               scene::Transform(%s, %s));" % (rotation, f.vec_mm(b.translation)),
              "}"]
    return lines


def _matrix_literal(prefix: str, m) -> list[str]:
    rows = ["{%s}" % ", ".join(f.num(x) for x in row) for row in m]
    indent = " " * (len(prefix) + 2)
    return ["%s{{%s," % (prefix, rows[0]),
            "%s%s," % (indent, rows[1]),
            "%s%s}};" % (indent, rows[2])]


# --- ExpectedChecks.hh ---------------------------------------------------------------
def render_expected(plan: G4Plan) -> str:
    out = [header(plan), "//",
           "// Что стенд check_geometry сверяет с Geant4: объёмы тел и пробные точки.",
           "// Пробные точки — в мировых координатах, мм; в каждой должно найтись указанное",
           "// тело с указанным материалом.",
           "#pragma once", "",
           "#include <vector>", "",
           "namespace expected {", "",
           "struct Volume {",
           "  const char* name;   // имя объёма в Geant4",
           "  double cadVolume;   // мм3, из verification.cad_volume",
           "  double relTol;      // допустимое относительное расхождение",
           "};", "",
           "struct Probe {",
           "  double x, y, z;     // мм, мировые координаты",
           "  const char* volume;",
           "  const char* material;",
           "};", "",
           "inline constexpr const char* kSceneName = %s;" % f.cpp_str(plan.scene_name), "",
           "inline const std::vector<Volume> kVolumes = {"]
    out += ["    {%s, %s, %s}," % (f.cpp_str(b.volume), f.num(b.cad_volume), f.num(b.volume_tol))
            for b in plan.bodies]
    out += ["};", "", "inline const std::vector<Probe> kProbes = {"]
    for b in plan.bodies:
        if not b.probes:
            continue
        out.append("    // %s: центр и точки у углов" % b.volume)
        for p in b.probes:
            out.append("    {%s, %s, %s}," % (", ".join(f.num(x) for x in p.point),
                                             f.cpp_str(p.volume), f.cpp_str(p.material)))
    out += ["};", "", "}  // namespace expected"]
    return "\n".join(out) + "\n"


# --- app/vis.mac ---------------------------------------------------------------------
def render_vis_mac(plan: G4Plan) -> str:
    out = [header(plan, "#"), "#",
           "# Визуализация геометрии сцены %s; выполняется при запуске ./scene_app." % plan.scene_name,
           "# Частиц пока нет: /run/beamOn в этом приложении не работает.",
           "/control/verbose 0",
           "/run/verbose 0",
           "/run/initialize",
           "",
           "/vis/open",
           "/vis/viewer/set/autoRefresh false",
           "/vis/verbose errors",
           "/vis/drawVolume",
           "/vis/viewer/set/style surface",
           "/vis/viewer/set/viewpointThetaPhi 60 30 deg",
           "/vis/scene/add/axes",
           "/vis/geometry/set/visibility %s 0 false" % WORLD,
           "",
           "# Цвета по материалам; тела, внутри которых есть другие, — полупрозрачные."]
    colour: dict[str, tuple] = {}
    names = {m.id: m.comment for m in plan.materials}
    parents = {b.mother for b in plan.bodies}
    for b in plan.bodies:
        if b.material_id not in colour:
            colour[b.material_id] = PALETTE[len(colour) % len(PALETTE)]
            out.append("# %s: %s" % (b.material_id, f.comment(names.get(b.material_id, ""))))
        r, g, bl = colour[b.material_id]
        alpha = PARENT_OPACITY if b.volume in parents else 1
        out.append("/vis/geometry/set/colour %s 0 %s %s %s %s" % (
            b.volume, f.num(r), f.num(g), f.num(bl), f.num(alpha)))
    out += ["",
            "/vis/viewer/set/autoRefresh true",
            "/vis/verbose warnings"]
    return "\n".join(out) + "\n"


# --- report.json ---------------------------------------------------------------------
def render_report(plan: G4Plan, diagnostics: list[Diagnostic]) -> str:
    report = {
        "generator": {"name": "mcscene", "version": plan.generator_version},
        "target": "geant4",
        "flags": {"unsafe_skip_checks": plan.unsafe},
        "input": {"file": plan.input_name, "sha256": plan.input_sha256,
                  "format_version": plan.format_version},
        "world": {"material": plan.world.material, "half_size_mm": list(plan.world.half_size),
                  "margin_percent": plan.world.margin_percent},
        "materials": [{"id": m.id, "geant4": m.g4_name} for m in plan.materials],
        "bodies": [{"id": b.id, "volume": b.volume, "mother": b.mother, "material": b.material_id,
                    "cad_volume_mm3": b.cad_volume, "probes": len(b.probes)} for b in plan.bodies],
        "diagnostics": [{k: v for k, v in asdict(d).items() if v is not None} for d in diagnostics],
    }
    return json.dumps(report, ensure_ascii=False, indent=2) + "\n"
